# shellcheck shell=bash
# run-shellcheck
test_audit() {
    if [ "$(id -u)" -ne 0 ]; then
        skip "SKIPPED: root required for audit runtime tests"
        return
    fi

    if ! command -v augenrules >/dev/null 2>&1; then
        skip "SKIPPED: augenrules not available (auditd not installed)"
        return
    fi

    local audit_rules="/etc/audit/audit.rules"
    local rules_file="/etc/audit/rules.d/50-delete.rules"
    # shellcheck disable=2154
    local script_cfg="${CIS_CONF_DIR}/conf.d/${script}.cfg"
    local backup_dir f uid_min

    backup_dir=$(mktemp -d)
    for f in "$audit_rules" "$rules_file" "$script_cfg" /etc/login.defs; do
        if [ -f "$f" ]; then
            cp -p "$f" "$backup_dir/"
        fi
    done
    uid_min=$(awk '/^\s*UID_MIN/{print $2}' /etc/login.defs)
    rm -f "$rules_file"

    describe Test case: UID_MIN absent
    sed -i '/^\s*UID_MIN/d' /etc/login.defs
    register_test retvalshouldbe 1
    register_test contain "Unable to determine UID_MIN"
    # shellcheck disable=2154
    run uid_min_absent "${CIS_CHECKS_DIR}/${script}.sh" --audit-all
    cp -p "$backup_dir/login.defs" /etc/login.defs

    describe Test case: effective audit rules file absent
    rm -f "$audit_rules"
    register_test retvalshouldbe 1
    register_test contain "Unable to read $audit_rules"
    run audit_rules_absent "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Test case: rules absent from effective audit rules
    echo "-D" >"$audit_rules"
    register_test retvalshouldbe 1
    register_test contain "not found or incomplete in $audit_rules (complete arch: none)"
    run rules_absent "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Test case: b64 rule only
    echo "-a always,exit -F arch=b64 -S rename,unlink,unlinkat,renameat -F auid>=${uid_min} -F auid!=unset -k delete" >"$audit_rules"
    register_test retvalshouldbe 1
    register_test contain "(complete arch: b64)"
    run b64_only "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Test case: renameat missing
    cat >"$audit_rules" <<EOF
-a always,exit -F arch=b64 -S rename,unlink,unlinkat -F auid>=${uid_min} -F auid!=unset -k delete
-a always,exit -F arch=b32 -S rename,unlink,unlinkat -F auid>=${uid_min} -F auid!=unset -k delete
EOF
    register_test retvalshouldbe 1
    register_test contain "(complete arch: none)"
    run missing_syscall "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Test case: wrong auid filter
    cat >"$audit_rules" <<EOF
-a always,exit -F arch=b64 -S rename,unlink,unlinkat,renameat -F auid>=${uid_min}0 -F auid!=unset -k delete
-a always,exit -F arch=b32 -S rename,unlink,unlinkat,renameat -F auid>=${uid_min}0 -F auid!=unset -k delete
EOF
    register_test retvalshouldbe 1
    run wrong_auid "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Test case: rules with separate -S options, not generated by augenrules
    cat >"$audit_rules" <<EOF
-a always,exit -F arch=b64 -S unlink -S unlinkat -S rename -S renameat -F auid>=${uid_min} -F auid!=4294967295 -k delete
-a always,exit -F arch=b32 -S unlink -S unlinkat -S rename -S renameat -F auid>=${uid_min} -F auid!=4294967295 -k delete
EOF
    register_test retvalshouldbe 0
    register_test contain "File deletion audit rules found in $audit_rules"
    run not_generated "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Correcting situation with DISABLE_AUGENRULES
    echo "-D" >"$audit_rules"
    sed -i 's/audit/enabled/' "$script_cfg"
    echo 'DISABLE_AUGENRULES=true' >>"$script_cfg"
    "${CIS_CHECKS_DIR}/${script}.sh" || true

    describe Checking effective audit rules have not been regenerated
    register_test retvalshouldbe 1
    run augenrules_disabled "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Correcting situation
    sed -i '/^DISABLE_AUGENRULES=/d' "$script_cfg"
    "${CIS_CHECKS_DIR}/${script}.sh" || true

    describe Checking resolved state
    register_test retvalshouldbe 0
    register_test contain "File deletion audit rules found in $audit_rules"
    run resolved "${CIS_CHECKS_DIR}/${script}.sh" --audit-all

    describe Restoring host state
    for f in "$audit_rules" "$rules_file" "$script_cfg" /etc/login.defs; do
        if [ -f "$backup_dir/$(basename "$f")" ]; then
            cp -p "$backup_dir/$(basename "$f")" "$f"
        else
            rm -f "$f"
        fi
    done
    rm -rf "$backup_dir"
    auditctl -R "$audit_rules" >/dev/null 2>&1 || true
}
